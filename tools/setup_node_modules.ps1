$ErrorActionPreference = "Stop"
$tempDir = "$env:TEMP\dial_tool_npm"
if (Test-Path $tempDir) { Remove-Item -Recurse -Force $tempDir }
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
Copy-Item web/package.json $tempDir/
Copy-Item web/package-lock.json $tempDir/
Push-Location $tempDir
cmd /c npm ci
Pop-Location
if (Test-Path "web/node_modules") { Remove-Item -Recurse -Force "web/node_modules" }
robocopy "$tempDir\node_modules" "web\node_modules" /E /NFL /NDL /NJH /NJS /nc /ns /np
Write-Host "node_modules installed successfully!"
