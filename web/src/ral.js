// is made of ral colors … classified colors show up as a grid in gradient's place"; "Fixed band for slider"; his
// drawing of 15:16: "smaller, rounded color swatches, design system on off possible and group the color code with the
// swatch down below").
//
// Two charts. RAL Classic: 215 colours, [code, name, hex]; the code's first digit is its family: 1 yellow · 2 orange ·
// 3 red · 4 violet · 5 blue · 6 green · 7 grey · 8 brown · 9 white and black. RAL Design System+: 1,825 colours named
// by hue, lightness and chroma ("RAL 210 50 30"), each packed as "H L C|name|hex" and filed under the family of the
// Classic colour nearest it; the shops don't stock them (Okay: "not stock"), so they can be switched off.
//
// The sRGB values stand in for the real colours: RAL publishes none, so these are the usual web approximations
// (Wikipedia's list, as packed by ral-colors 1.0.1, MIT, Ibon Eskudero) — good for naming and choosing, never for
// matching a paint; the printed card is the reference. The names and codes are RAL gGmbH's.
//
// The grid: one family at a time, RAL_ROWS rows of lightness (light at the top, steps between the family's lightest
// and darkest) and RAL_COLS columns of chroma (grey at the left, vivid at the right). A cell holds the colour nearest
// its step; a Classic colour takes its cell before any Design colour.

