/** '#RRGGBB' → [r, g, b] in 0–1 */
const rgb_of = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);

/** how light a colour looks, 0–100 (CIE L*: the eye's scale, so a row of the grid is one step of lightness, not of
 *  light's energy) */
export function ral_lightness(hex) {
  const lin = rgb_of(hex).map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  const y = 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
  return y <= 0.008856 ? 903.3 * y : 116 * Math.cbrt(y) - 16;
}

/** how far from grey a colour is, 0–1 (the spread of its three channels) */
export const ral_chroma = (hex) => { const c = rgb_of(hex); return Math.max(...c) - Math.min(...c); };

/** how unlike two colours look: a weighted distance in rgb (the eye weighs green most, blue least) */
const apart = ([r, g, b], [cr, cg, cb]) => 2 * (cr - r) ** 2 + 4 * (cg - g) ** 2 + 3 * (cb - b) ** 2;

/** a colour as the grid and the line use it: {code, name, hex, design} — design: true for a Design System+ colour */
const classic = RAL_CLASSIC.map(([code, name, hex]) => ({ code, name, hex, design: false, family: code[0] }));

/** the Design System+ colours, unpacked once, each under the family of the nearest Classic colour */
let design_list = null;
function design() {
  if (design_list) return design_list;
  design_list = RAL_DESIGN_PACKED.map((row) => {
    const [code, name, hex] = row.split("|"), rgb = rgb_of(hex);
    let near = classic[0], least = Infinity;
    for (const c of classic) { const d = apart(rgb, rgb_of(c.hex)); if (d < least) { least = d; near = c; } }
    return { code, name, hex, design: true, family: near.family };
  });
  return design_list;
}

/** every colour of a family: Classic first, then (with_design) Design System+ */
const family_colours = (family, with_design) => [...classic.filter((c) => c.family === family), ...(with_design ? design().filter((c) => c.family === family) : [])];

/** a family's grid: RAL_ROWS rows of RAL_COLS cells, a cell a colour or null. The rows are steps of lightness between
 *  the family's lightest and darkest, the columns steps of chroma between its greyest and most vivid; a cell holds the
 *  colour nearest its step, a Classic colour before a Design one, and a colour whose cell is taken moves to the
 *  nearest free cell in its row. */
export function ral_grid(family, with_design = true) {
  const all = family_colours(family, with_design).map((c) => ({ ...c, l: ral_lightness(c.hex), s: ral_chroma(c.hex) }));
  const ls = all.map((c) => c.l), ss = all.map((c) => c.s);
  const top = Math.max(...ls), span_l = top - Math.min(...ls) || 1, left = Math.min(...ss), span_s = Math.max(...ss) - left || 1;
  const rows = Array.from({ length: RAL_ROWS }, () => Array(RAL_COLS).fill(null));
  const place = (c) => {
    const row = rows[Math.min(RAL_ROWS - 1, Math.floor((top - c.l) / span_l * RAL_ROWS))];
    const col = Math.min(RAL_COLS - 1, Math.floor((c.s - left) / span_s * RAL_COLS));
    for (let step = 0; step < RAL_COLS; step++) {      // its own cell, else the nearest free one in the row
      for (const k of [col - step, col + step]) if (k >= 0 && k < RAL_COLS && !row[k]) { row[k] = c; return; }
    }
  };
  all.filter((c) => !c.design).forEach(place);
  all.filter((c) => c.design).forEach(place);
  return rows;
}

/** the colour that stands for a family on its band */
export const ral_family_colour = (family) => RAL_CLASSIC.find((c) => c[0] === RAL_FAMILIES.find((f) => f[0] === family)[2])[2];

/** the RAL colour nearest to an rgb (0–1), and whether it is that colour exactly: {colour, exact}. Classic first:
 *  a colour on a Classic and a Design colour at once is named by the Classic. */
export function ral_nearest([r, g, b], with_design = true) {
  let best = null, least = Infinity;
  for (const colour of [...classic, ...(with_design ? design() : [])]) {
    const d = apart([r, g, b], rgb_of(colour.hex));
    if (d < least - 1e-9) { least = d; best = colour; }
  }
  const exact = rgb_of(best.hex).every((v, i) => Math.abs(v - [r, g, b][i]) < 1 / 255);
  return { colour: best, exact };
}

/** "5015", "RAL 5015", "210 50 30", "RAL 210 50 30" → the colour, or null */
export function ral_by_code(text) {
  const m = /^\s*(?:ral)?\s*(\d{4}|\d{1,3}\s+\d{1,3}\s+\d{1,3})\s*$/i.exec(String(text));
  if (!m) return null;
  const code = m[1].replace(/\s+/g, " ");
  return classic.find((c) => c.code === code) || design().find((c) => c.code === code) || null;
}
